// src/sculpture/beasts.js — 獸像：滴水獸、怪獸（chimères）、沉思者、福音書作者象徵、馬
// 全部在局部座標建立：+Z = 面向（獸頭朝向），+Y = 上。
import * as THREE from 'three';
import { smooth, transM } from './geo.js';

const TAU = Math.PI * 2;

/**
 * 獸頭：頭長約 1（從後腦到吻端），原點在頭骨中心，吻往 +Z。
 * o: { kind: 'dog'|'lion'|'goat'|'eagle'|'ox'|'devil', jaw: 張嘴弧度, horns, ears, nu }
 */
export function beastHead(M, o) {
  const nu = o.nu || 16, nv = Math.max(8, Math.round(nu * 0.7));
  const kind = o.kind || 'dog';
  // 頭骨（眉弓、眼窩）
  M.ellipsoid(0, 0, 0, 0.36, 0.33, 0.38, nu, nv, 0.9, (dx, dy, dz) => {
    const eye = Math.exp(-(((Math.abs(dx) - 0.45) ** 2) + ((dy - 0.28) ** 2)) / 0.03) * smooth(0.2, 0.7, dz);
    const brow = Math.exp(-((dy - 0.5) ** 2) / 0.02) * smooth(0.0, 0.6, dz);
    const wr = 0.05 * Math.abs(Math.sin(dx * 11) * Math.sin(dy * 9 + dz * 3));
    return [1 - 0.12 * eye + 0.12 * brow + wr, 0.9 - 0.45 * eye - wr * 3];
  });
  // 眼珠
  for (const s of [-1, 1]) M.ellipsoid(s * 0.17, 0.1, 0.27, 0.075, 0.07, 0.06, 8, 6, 0.95);
  if (kind === 'eagle') {
    // 勾喙
    M.tube([[0, 0.02, 0.25], [0, 0.0, 0.55], [0, -0.1, 0.78], [0, -0.25, 0.8]], [0.17, 0.12, 0.06, 0.01], 10, 12, 0.92, { sx: 0.8 });
    M.pushTRS(0, -0.12, 0.3, o.jaw || 0.25, 0, 0);
    M.tube([[0, 0, 0], [0, -0.02, 0.3], [0, -0.04, 0.42]], [0.12, 0.07, 0.01], 8, 8, 0.85, { sx: 0.8 });
    M.pop();
  } else {
    const len = kind === 'ox' ? 0.55 : kind === 'lion' ? 0.45 : kind === 'goat' ? 0.55 : 0.6;
    // 上顎 + 鼻
    M.ellipsoid(0, -0.06, 0.25 + len * 0.5, 0.24, 0.18, len * 0.55, nu, nv, 0.9, (dx, dy, dz) => {
      const wr = 0.06 * Math.abs(Math.sin(dz * 10)) * smooth(0, 0.8, dy);
      return [1 + wr, 0.9 - wr * 2];
    });
    for (const s of [-1, 1]) M.ellipsoid(s * 0.1, 0.0, 0.25 + len * 1.02, 0.05, 0.04, 0.04, 6, 4, 0.35); // 鼻孔
    // 下顎（張開）
    M.pushTRS(0, -0.2, 0.1, o.jaw ?? 0.45, 0, 0);
    M.ellipsoid(0, -0.02, len * 0.55, 0.2, 0.09, len * 0.55, nu, Math.round(nv * 0.7), 0.85);
    // 牙
    for (let k = 0; k < 4; k++) for (const s of [-1, 1]) {
      M.push(transM(s * 0.13, 0.05, len * (0.4 + k * 0.17)));
      M.lathe([[0, 0], [0.03, 0], [0, 0.09]], 4, 1);
      M.pop();
    }
    M.pop();
    // 口內（暗）
    M.ellipsoid(0, -0.2, 0.25 + len * 0.3, 0.17, 0.08, len * 0.45, 10, 6, 0.25);
    for (let k = 0; k < 3; k++) for (const s of [-1, 1]) {
      M.push(transM(s * 0.15, -0.15, 0.3 + len * (0.4 + k * 0.2)));
      M.lathe([[0, 0], [0.028, 0], [0, -0.08]].map(([r, y]) => [r, y]), 4, 1);
      M.pop();
    }
  }
  // 角 / 耳
  if (o.horns) {
    for (const s of [-1, 1]) {
      const big = o.horns === 'big';
      M.tube([[s * 0.2, 0.25, -0.05], [s * 0.35, big ? 0.65 : 0.45, -0.15], [s * 0.3, big ? 1.0 : 0.6, -0.3]], [0.09, 0.06, 0.01], 7, 8, 0.9);
    }
  }
  if (o.ears !== false && kind !== 'eagle') {
    for (const s of [-1, 1]) {
      M.pushTRS(s * 0.3, 0.25, -0.05, 0, s * 0.4, s * -0.5);
      M.ellipsoid(0, 0.1, 0, 0.06, 0.16, 0.035, 7, 5, 0.85);
      M.pop();
    }
  }
  if (kind === 'lion') {
    // 鬃毛：頭後一圈波浪狀厚環
    M.push(transM(0, -0.05, -0.12));
    M.grid(nu + 8, 6, (u, v, out) => {
      const a = u * TAU;
      const r = 0.45 + 0.18 * v + 0.05 * Math.sin(a * 9);
      out[0] = Math.cos(a) * r; out[1] = Math.sin(a) * r * 1.05; out[2] = -0.25 * v + 0.12 * (1 - v); out[3] = 0.75 + 0.2 * Math.abs(Math.sin(a * 9));
    }, { cap0: true, cap1: true });
    M.pop();
  }
}

/** 滴水獸：根部在原點、沿 +Z 伸出長度 1 */
export function gargoyle(M, o) {
  const nu = o.nu || 10;
  // 根部石塊（嵌入牆內）
  M.box(0, 0, -0.08, 0.24, 0.17, 0.4, 0.85);
  // 身體（略拱）+ 鱗紋
  M.tube([[0, 0.0, 0.05], [0, 0.035, 0.3], [0, 0.03, 0.55], [0, 0.05, 0.68]], [0.105, 0.095, 0.075, 0.06], nu, 14, 0.9, {
    sy: 0.85, colors: (v, u) => 0.75 + 0.2 * Math.abs(Math.sin(v * 30 + Math.sin(u * TAU) * 2)),
  });
  // 背上的排水槽
  M.box(0, 0.085, 0.3, 0.05, 0.02, 0.5, 0.4);
  // 前腿 + 爪
  for (const s of [-1, 1]) {
    M.tube([[s * 0.06, 0.0, 0.42], [s * 0.1, -0.06, 0.48], [s * 0.08, -0.11, 0.56]], [0.035, 0.028, 0.02], 6, 6, 0.85);
    for (let k = -1; k <= 1; k++) M.rod([s * 0.08, -0.11, 0.56], [s * 0.08 + k * 0.015, -0.13, 0.6], 0.008, 0.002, 4, 0.8);
  }
  // 摺翼（貼在身側）
  for (const s of [-1, 1]) {
    M.pushTRS(s * 0.085, 0.04, 0.22, 0, s < 0 ? Math.PI / 2 + 0.15 : -Math.PI / 2 - 0.15, 0, 1, 1, s);
    M.extrude([[0, 0], [0.18, 0.06], [0.24, 0.0], [0.17, -0.03], [0.12, -0.065], [0.07, -0.04], [0.02, -0.07]], 0.015, 0.85, 0.7);
    M.pop();
  }
  // 頭
  M.pushTRS(0, 0.06, 0.8, 0.15, 0, 0, 0.19);
  beastHead(M, { kind: o.kind || 'dog', jaw: 0.6, horns: o.horns, nu: o.headNu || 12 });
  M.pop();
}

/** 坐著的怪獸：高度 1（不含角），面向 +Z */
export function chimera(M, o) {
  const nu = o.nu || 14;
  M.ellipsoid(0, 0.2, -0.06, 0.2, 0.2, 0.24, nu, 9, 0.85); // 後腿臀
  for (const s of [-1, 1]) M.ellipsoid(s * 0.14, 0.12, 0.02, 0.07, 0.12, 0.17, 8, 6, 0.8); // 後腿
  M.pushTRS(0, 0.48, 0.02, -0.35, 0, 0);
  M.ellipsoid(0, 0, 0, 0.15, 0.26, 0.15, nu, 10, 0.9, (dx, dy, dz) => [1 + 0.04 * Math.abs(Math.sin(dy * 14)) * smooth(0, 0.8, dz), 0.9]);
  M.pop();
  for (const s of [-1, 1]) {
    M.tube([[s * 0.1, 0.56, 0.1], [s * 0.11, 0.3, 0.16], [s * 0.1, 0.04, 0.16]], [0.05, 0.04, 0.035], 7, 8, 0.85);
    for (let k = -1; k <= 1; k++) M.ellipsoid(s * 0.1 + k * 0.022, 0.02, 0.2, 0.014, 0.014, 0.04, 5, 4, 0.8);
  }
  // 尾
  M.tube([[0, 0.12, -0.25], [0.1, 0.05, -0.3], [0.2, 0.03, -0.15], [0.22, 0.02, 0.0]], [0.04, 0.03, 0.02, 0.01], 6, 10, 0.8);
  if (o.wings) {
    for (const s of [-1, 1]) {
      M.pushTRS(s * 0.08, 0.62, -0.1, 0.25, s < 0 ? -Math.PI / 2 - 0.5 : Math.PI / 2 + 0.5, 0, 1, 1, 1);
      M.extrude(o.wings === 'bat'
        ? [[0, 0], [0.12, 0.25], [0.25, 0.42], [0.3, 0.3], [0.26, 0.15], [0.3, 0.02], [0.2, 0.06], [0.16, -0.12], [0.08, -0.04]]
        : [[0, 0], [0.08, 0.28], [0.18, 0.45], [0.26, 0.4], [0.3, 0.2], [0.27, 0.05], [0.28, -0.1], [0.2, -0.05], [0.18, -0.2], [0.1, -0.1], [0.05, -0.18]], 0.025, 0.85, 0.7);
      M.pop();
    }
  }
  M.pushTRS(0, 0.8, 0.12, o.headTilt || 0.15, o.headTurn || 0, 0, 0.24);
  beastHead(M, { kind: o.kind, jaw: o.jaw ?? 0.35, horns: o.horns, nu: o.headNu || 14 });
  M.pop();
}

/** 沉思者 Le Stryge：托腮、有角、有翼；高度 1，面向 +Z */
export function stryge(M) {
  const nu = 22;
  // 蹲坐的後腿
  M.ellipsoid(0, 0.16, -0.12, 0.17, 0.16, 0.2, nu, 12, 0.85);
  for (const s of [-1, 1]) {
    M.tube([[s * 0.13, 0.2, -0.15], [s * 0.15, 0.24, 0.06], [s * 0.13, 0.03, 0.1]], [0.07, 0.06, 0.045], 8, 10, 0.85);
    for (let k = -1; k <= 1; k++) M.ellipsoid(s * 0.13 + k * 0.024, 0.02, 0.15, 0.016, 0.014, 0.045, 5, 4, 0.8);
  }
  // 前傾軀幹
  M.pushTRS(0, 0.4, -0.02, 0.45, 0, 0);
  M.ellipsoid(0, 0, 0, 0.15, 0.24, 0.13, nu, 14, 0.88, (dx, dy, dz) => [1 + 0.05 * Math.exp(-((dy - 0.2) ** 2) / 0.04) * smooth(0.2, 0.8, dz), 0.88]);
  M.pop();
  // 手臂：肩 → 肘（撐在欄杆上）→ 手托住臉頰
  for (const s of [-1, 1]) {
    const sh = [s * 0.13, 0.55, 0.04], el = [s * 0.1, 0.24, 0.27], wr = [s * 0.075, 0.5, 0.33];
    M.tube([sh, [s * 0.14, 0.38, 0.17], el], [0.05, 0.045, 0.045], 8, 10, 0.85);
    M.tube([el, wr], [0.045, 0.035], 8, 8, 0.85);
    // 手掌貼在頰邊，手指往上
    M.pushTRS(s * 0.075, 0.56, 0.34, 0, s * 0.3, 0);
    M.ellipsoid(0, 0, 0, 0.022, 0.06, 0.045, 8, 6, 0.85);
    for (let k = 0; k < 4; k++) M.rod([s * 0.01, 0.04, -0.03 + k * 0.022], [s * 0.012, 0.11, -0.03 + k * 0.024], 0.009, 0.007, 4, 0.8);
    M.pop();
  }
  // 頭：下巴放在手上，角很長，伸舌
  M.pushTRS(0, 0.64, 0.35, 0.1, 0, 0, 0.24);
  beastHead(M, { kind: 'dog', jaw: 0.15, horns: 'big', nu: 18 });
  M.ellipsoid(0, -0.28, 0.75, 0.09, 0.03, 0.14, 8, 5, 0.75); // 舌
  M.pop();
  // 大翅膀：從背後往上豎起
  for (const s of [-1, 1]) {
    M.pushTRS(s * 0.07, 0.55, -0.12, -0.1, s < 0 ? -Math.PI / 2 - 0.25 : Math.PI / 2 + 0.25, 0, 1, 1, 1);
    const pts = [[0.02, -0.1], [-0.02, 0.15], [0.02, 0.35], [0.1, 0.46], [0.2, 0.42], [0.25, 0.25], [0.26, 0.05], [0.22, -0.1], [0.18, -0.25], [0.12, -0.2], [0.07, -0.3]];
    M.extrude(pts, 0.04, 0.85, 0.75);
    for (let k = 0; k < 4; k++) M.box(0.05 + k * 0.045, 0.1 - k * 0.04, 0.022, 0.012, 0.35, 0.01, 0.7);
    M.pop();
  }
}

/** 福音書作者象徵（銅像）：有翼的獅、牛、鷹，坐姿高度 1 */
export function evangelistBeast(M, kind) {
  if (kind === 'eagle') {
    M.ellipsoid(0, 0.42, 0.0, 0.16, 0.3, 0.17, 16, 10, 0.9, (dx, dy, dz) => [1 + 0.05 * Math.abs(Math.sin(dy * 20)), 0.85 + 0.1 * Math.abs(Math.sin(dy * 20))]);
    for (const s of [-1, 1]) {
      M.tube([[s * 0.06, 0.15, 0.0], [s * 0.07, 0.04, 0.04]], [0.03, 0.025], 6, 4, 0.85);
      M.pushTRS(s * 0.12, 0.52, -0.05, 0.1, s < 0 ? -Math.PI / 2 - 0.3 : Math.PI / 2 + 0.3, 0, 1, 1, 1);
      M.extrude([[0, 0], [0.1, 0.3], [0.2, 0.5], [0.26, 0.42], [0.28, 0.2], [0.25, 0.0], [0.24, -0.25], [0.16, -0.18], [0.12, -0.3], [0.05, -0.15]], 0.03, 0.85, 0.75);
      M.pop();
    }
    M.tube([[0, 0.25, -0.12], [0, 0.08, -0.25]], [0.08, 0.02], 6, 4, 0.85, { sx: 1.6 });
    M.pushTRS(0, 0.8, 0.06, 0.1, 0, 0, 0.2);
    beastHead(M, { kind: 'eagle', jaw: 0.1, ears: false, nu: 14 });
    M.pop();
    return;
  }
  chimera(M, { kind: kind === 'ox' ? 'ox' : 'lion', wings: 'feather', horns: kind === 'ox' ? 'small' : null, jaw: kind === 'ox' ? 0.08 : 0.3, headTilt: 0 });
}

/** 馬：鬐甲高 1，頭往 +Z，腳底 y = 0 */
export function horse(M, o = {}) {
  const nu = 20;
  M.ellipsoid(0, 0.78, 0.0, 0.2, 0.22, 0.46, nu, 12, 0.9);
  M.ellipsoid(0, 0.8, 0.33, 0.2, 0.22, 0.2, nu, 10, 0.9);
  M.ellipsoid(0, 0.8, -0.34, 0.21, 0.22, 0.22, nu, 10, 0.9);
  // 頸與頭
  M.tube([[0, 0.82, 0.38], [0, 1.0, 0.52], [0, 1.15, 0.6]], [0.15, 0.12, 0.09], 14, 10, 0.9, { sx: 0.75 });
  M.pushTRS(0, 1.12, 0.66, 0.95, 0, 0);
  M.ellipsoid(0, 0, 0.12, 0.08, 0.07, 0.2, 14, 9, 0.9);
  M.ellipsoid(0, -0.01, 0.3, 0.065, 0.06, 0.08, 10, 6, 0.85);
  for (const s of [-1, 1]) {
    M.push(transM(s * 0.05, 0.06, -0.04)); M.lathe([[0, 0], [0.025, 0], [0, 0.09]], 5, 0.85); M.pop();
  }
  M.pop();
  // 鬃
  M.tube([[0, 0.97, 0.4], [0, 1.12, 0.52], [0, 1.24, 0.6]], [0.035, 0.035, 0.02], 6, 8, 0.75, { sx: 0.5 });
  // 腿（右前腿抬起，步行）
  const legs = [
    [-1, 0.36, [[0, 0.7, 0], [0.02, 0.4, 0.1], [0.0, 0.2, 0.22], [0.0, 0.1, 0.24]]],
    [1, 0.36, [[0, 0.7, 0], [0, 0.38, 0.02], [0, 0.04, 0.0]]],
    [-1, -0.36, [[0, 0.72, 0], [0, 0.42, -0.08], [0, 0.04, -0.02]]],
    [1, -0.36, [[0, 0.72, 0], [0, 0.4, -0.1], [0, 0.04, 0.0]]],
  ];
  for (const [s, z, pts] of legs) {
    const P = pts.map(([x, y, zz]) => [s * 0.1 + x, y, z + zz]);
    M.tube(P, [0.11, 0.06, 0.05], 10, 10, 0.9);
    M.ellipsoid(P[0][0], P[0][1] - 0.02, P[0][2], 0.1, 0.2, 0.15, 10, 6, 0.9);
  }
  // 蹄（另外定位）
  for (const [s, z, pts] of legs) {
    const p = pts[pts.length - 1];
    M.ellipsoid(s * 0.1 + p[0], p[1] - 0.01, z + p[2] + 0.01, 0.045, 0.035, 0.055, 7, 4, 0.8);
  }
  // 尾
  M.tube([[0, 0.86, -0.55], [0, 0.6, -0.63], [0, 0.3, -0.62]], [0.05, 0.06, 0.03], 8, 10, 0.75, { sx: 0.7 });
  // 鞍布
  M.ellipsoid(0, 0.92, -0.02, 0.24, 0.12, 0.25, 14, 6, 0.8);
}
